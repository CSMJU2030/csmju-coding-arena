/**
 * ทะเบียนภาษา — แหล่งเดียวของคำสั่ง compile/run ทุกภาษา (image `judge/polyglot` มีแค่ toolchain)
 *
 * - ผู้ใช้ส่งได้แค่ซอร์สโค้ดกับ input · argv ทั้งหมดมาจากที่นี่ (ผู้ใช้เปลี่ยนคำสั่งไม่ได้)
 * - `template` คือโค้ดตั้งต้นของ playground และเป็นชุดทดสอบ smoke ด้วย:
 *   รันกับ `stdin` แล้ว stdout ต้องมี `expect` (สคริปต์ `pnpm --filter backend languages:smoke`)
 * - runtime `browser` = รันในเบราว์เซอร์ของผู้ใช้ (ไม่ผ่าน server) · `sandbox` = container ของ image polyglot
 */

export type LanguageCategory =
  | 'popular'
  | 'systems'
  | 'jvm'
  | 'dotnet'
  | 'scripting'
  | 'shell'
  | 'functional'
  | 'lisp'
  | 'logic'
  | 'classic'
  | 'esoteric'
  | 'web'
  | 'data';

export interface LanguageSpec {
  id: string;
  name: string;
  category: LanguageCategory;
  /** ชื่อไฟล์ที่เขียนซอร์สลงไป */
  file: string;
  /** โหมดไฮไลต์/นามสกุลสำหรับหน้าเว็บ */
  extension: string;
  runtime: 'sandbox' | 'browser';
  compile?: string[];
  run: string[];
  template: string;
  stdin: string;
  expect: string;
  /** RAM ของ container (MB) — ค่าเริ่ม 256 · JVM/.NET/GHC ต้องมากกว่า */
  memoryMb?: number;
}

const EXPECT = 'Hello, CS Arena!';
const NAME = 'CS Arena';

const lines = (...rows: string[]) => `${rows.join('\n')}\n`;

function spec(
  id: string,
  name: string,
  category: LanguageCategory,
  file: string,
  run: string[],
  template: string,
  extra: Partial<LanguageSpec> = {},
): LanguageSpec {
  return {
    id,
    name,
    category,
    file,
    extension: file.split('.').pop() ?? 'txt',
    runtime: 'sandbox',
    run,
    template,
    stdin: NAME,
    expect: EXPECT,
    ...extra,
  };
}

const sh = (shell: string, id: string, name: string, file = 'main.sh') =>
  spec(
    id,
    name,
    'shell',
    file,
    [shell, file],
    lines('read name', 'echo "Hello, $name!"'),
  );

